package dns

import (
	"bytes"
	"encoding/csv"
	"encoding/json"
	"fmt"
	"strconv"
	"strings"
	"time"
)

// Export renders a report as "json", "csv" or "md" (Markdown).
func Export(r *Report, format string) (string, error) {
	if r == nil {
		return "", fmt.Errorf("no benchmark results to export yet")
	}
	switch strings.ToLower(format) {
	case "json":
		b, err := json.MarshalIndent(r, "", "  ")
		return string(b), err
	case "csv":
		return exportCSV(r)
	case "md", "markdown":
		return exportMarkdown(r), nil
	}
	return "", fmt.Errorf("unsupported export format %q", format)
}

func protoAvg(s *ServerResult, p Protocol) string {
	if pr, ok := s.Protocols[p]; ok && pr.Combined.Valid() {
		return ff(pr.Combined.Avg)
	}
	return ""
}

func ff(v float64) string { return strconv.FormatFloat(v, 'f', 2, 64) }

func exportCSV(r *Report) (string, error) {
	var buf bytes.Buffer
	w := csv.NewWriter(&buf)
	_ = w.Write([]string{
		"rank", "name", "category", "source", "address", "doh", "dot", "status", "primary_protocol",
		"avg_ms", "min_ms", "max_ms", "median_ms", "p95_ms", "jitter_ms", "loss_pct",
		"cached_avg_ms", "uncached_avg_ms", "udp_avg_ms", "tcp_avg_ms", "doh_avg_ms", "dot_avg_ms",
		"dnssec", "blocks_ads", "hijack_status", "udp_egress", "doh_egress",
	})
	for _, s := range r.Results {
		o := s.Overall
		_ = w.Write([]string{
			strconv.Itoa(s.Rank), s.Resolver.Name, string(s.Resolver.Category), string(s.Resolver.Source),
			s.Resolver.PrimaryAddr(), s.Resolver.DoH, s.Resolver.DoT, s.Status, string(s.Primary),
			ff(o.Avg), ff(o.Min), ff(o.Max), ff(o.Median), ff(o.P95), ff(o.Jitter), ff(o.Loss),
			ff(s.Cached.Avg), ff(s.Uncached.Avg),
			protoAvg(s, ProtoUDP), protoAvg(s, ProtoTCP), protoAvg(s, ProtoDoH), protoAvg(s, ProtoDoT),
			s.DNSSEC, strconv.FormatBool(s.Filtering.BlocksAds), string(s.Hijack.Status), s.Hijack.UDPEgress, s.Hijack.DoHEgress,
		})
	}
	w.Flush()
	return buf.String(), w.Error()
}

func mdCell(s string) string {
	if s == "" {
		return "—"
	}
	return strings.ReplaceAll(s, "|", "\\|")
}

func exportMarkdown(r *Report) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# Resolv Benchmark Report\n\n")
	fmt.Fprintf(&b, "- **Date:** %s\n", r.StartedAt.Format(time.RFC1123))
	fmt.Fprintf(&b, "- **Duration:** %.1f s\n", float64(r.DurationMs)/1000)
	fmt.Fprintf(&b, "- **Protocols:** %s · **Queries:** %d per server/protocol/kind · **Timeout:** %d ms\n",
		strings.ToUpper(strings.Join(r.Options.Protocols, ", ")), r.Options.Queries, r.Options.TimeoutMs)
	if r.Recommendation != nil {
		fmt.Fprintf(&b, "- **Recommendation:** %s\n", r.Recommendation.Headline)
	}
	if r.Network.Checked {
		fmt.Fprintf(&b, "- **Network integrity:** %s\n", r.Network.Summary)
	}
	b.WriteString("\n| # | Resolver | Category | Address | Avg (ms) | P95 | Cached | Uncached | Min | Max | Jitter | Loss | UDP | DoH | DNSSEC | AdBlock | Hijack |\n")
	b.WriteString("|---:|---|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|---|---|\n")
	for _, s := range r.Results {
		addr := s.Resolver.PrimaryAddr()
		if addr == "" {
			addr = s.Resolver.DoH
		}
		avg := ff(s.Overall.Avg)
		if s.Status == "failed" {
			avg = "failed"
		}
		adBlock := "No"
		if s.Filtering.BlocksAds {
			adBlock = fmt.Sprintf("Yes (%d/%d)", s.Filtering.BlockedCount, s.Filtering.TestedCount)
		}
		fmt.Fprintf(&b, "| %d | %s | %s | `%s` | **%s** | %s | %s | %s | %s | %s | %s | %s%% | %s | %s | %s | %s | %s |\n",
			s.Rank, mdCell(s.Resolver.Name), s.Resolver.Category, addr, avg,
			ff(s.Overall.P95), ff(s.Cached.Avg), ff(s.Uncached.Avg), ff(s.Overall.Min), ff(s.Overall.Max), ff(s.Overall.Jitter),
			ff(s.Overall.Loss), mdCell(protoAvg(s, ProtoUDP)), mdCell(protoAvg(s, ProtoDoH)),
			s.DNSSEC, adBlock, s.Hijack.Status)
	}
	b.WriteString("\n_Generated by Resolv — free software under the GNU GPLv3._\n")
	return b.String()
}
